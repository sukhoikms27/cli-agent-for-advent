package com.cliagent.rag

/**
 * День 24: зафиксированные тексты ответов агента (anti-hallucination). Вынесены в отдельный объект —
 * единый источник истины, тестируемость (без форматирования в логике агента).
 *
 * Лекция недели 5: **анти-галлюцинации** — модель должна отвечать из retrieved-чанков, а не из
 * «общей памяти». Задание дня 24 (усиление): если релевантность ниже порога — ассистент обязан
 * сказать «не знаю» и попросить уточнение. Программный canned-response гарантирует это без
 * вызова LLM (дёшево, 100% отказ, persist'ится в history как обычный assistant-ответ).
 *
 * Не срабатывает при `retrieve()=null` (Ollama down / пустой индекс) — там мягкая деградация дня 22
 * (агент отвечает без RAG-блока), а не отказ. Canned используется только когда индекс есть, но
 * max similarity < [com.cliagent.rag.RagConfig.dontKnowThreshold] (или 0 чанков совпали).
 *
 * @see ContextAwareAgent (точка использования в `chat()`)
 */
object CannedResponses {

    /**
     * Слабый контекст: max similarity < порога ИЛИ 0 чанков совпали.
     *
     * Текст явно:
     *  1) сообщает, что релевантной информации не найдено (с числами для прозрачности);
     *  2) говорит «не знаю» (требование задания);
     *  3) просит уточнить/переформулировать вопрос (требование задания);
     *  4) цитирует исходный запрос в кавычках «...» — чтобы пользователь видел, что понято.
     *
     * @param query исходный запрос пользователя (для контекста в отказе).
     * @param maxScore лучшая релевантность среди retrieved-чанков (0.0 если список пуст).
     * @param threshold порог [com.cliagent.rag.RagConfig.dontKnowThreshold], ниже которого сработал отказ.
     */
    fun weakContext(query: String, maxScore: Float, threshold: Float): String =
        "Я не нашёл достаточно релевантной информации по этому вопросу в базе документов " +
            "(лучшая релевантность ${String.format("%.2f", maxScore)} ниже порога " +
            "${String.format("%.2f", threshold)}). Я не знаю точного ответа на «$query». " +
            "Пожалуйста, уточните или переформулируйте вопрос, чтобы я мог найти подходящие источники."
}
